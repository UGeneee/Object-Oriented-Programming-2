package week11_abstract;

public class Cat extends Animal {

    public void eat() {
        System.out.print("Cat loves eating fish and sometimes human food");
    }

    public void sleep() {
        System.out.println(" and they sleep for 12-16 hours a day");
    }

    public void makeSound() {
        System.out.println("Meow meow");
    }
    
}
