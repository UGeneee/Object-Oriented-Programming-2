package week11_abstract;

public class Dog extends Animal {

    public void eat() {
        System.out.print("Dogs love to eat human food or dog food");
    }

    public void sleep() {
        System.out.println(" and they sleep for 12-14 hours a day");
    }

    public void makeSound() {
        System.out.println("Woof woof");
    }

}
